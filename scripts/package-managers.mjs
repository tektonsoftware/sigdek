#!/usr/bin/env node
// Writes the package-manager manifests for a release from its checksums.txt:
//   Formula/sigdek.rb      Homebrew (macOS and Linux), tapped straight from this repository
//   bucket/sigdek.json     Scoop (Windows), added straight from this repository
//   <winget dir>/...       winget (Windows), submitted to microsoft/winget-pkgs
// Usage: node scripts/package-managers.mjs <version> <checksums.txt> <winget out dir>
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [version, sumsPath, wingetOut] = process.argv.slice(2);
if (!version || !sumsPath || !wingetOut) {
  console.error("usage: node scripts/package-managers.mjs <version> <checksums.txt> <winget out dir>");
  process.exit(2);
}
const sums = Object.fromEntries(
  readFileSync(sumsPath, "utf8")
    .trim()
    .split("\n")
    .map((l) => l.trim().split(/\s+/).reverse()),
);
const base = `https://github.com/tektonsoftware/sigdek/releases/download/v${version}`;
const file = (os, arch) => `sigdek_${version}_${os}_${arch}${os === "windows" ? ".exe" : ""}`;
const sha = (os, arch) => {
  const s = sums[file(os, arch)];
  if (!/^[0-9a-f]{64}$/.test(s ?? "")) throw new Error(`no checksum for ${file(os, arch)}`);
  return s;
};
const DESC = "Records what AI coding agents do on your machine, for your team's audit evidence";

// Homebrew. The downloads are bare binaries, so install renames whichever one was fetched.
const brewArch = (os, arch) => `      url "${base}/${file(os, arch)}"\n      sha256 "${sha(os, arch)}"`;
mkdirSync("Formula", { recursive: true });
writeFileSync(
  "Formula/sigdek.rb",
  `# Generated by scripts/package-managers.mjs for each release. Don't edit by hand.
class Sigdek < Formula
  desc "${DESC}"
  homepage "https://sigdek.com"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
${brewArch("darwin", "arm64")}
    end
    on_intel do
${brewArch("darwin", "amd64")}
    end
  end

  on_linux do
    on_arm do
${brewArch("linux", "arm64")}
    end
    on_intel do
${brewArch("linux", "amd64")}
    end
  end

  def install
    bin.install Dir["sigdek_*"].first => "sigdek"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sigdek version")
  end
end
`,
);

// Scoop. "#/sigdek.exe" renames the download so the command is plain `sigdek`.
mkdirSync("bucket", { recursive: true });
const scoopUrl = (arch, v = version) => `https://github.com/tektonsoftware/sigdek/releases/download/v${v}/sigdek_${v}_windows_${arch}.exe#/sigdek.exe`;
writeFileSync(
  "bucket/sigdek.json",
  JSON.stringify(
    {
      version,
      description: `${DESC}.`,
      homepage: "https://sigdek.com",
      license: "Apache-2.0",
      architecture: {
        "64bit": { url: scoopUrl("amd64"), hash: sha("windows", "amd64") },
        arm64: { url: scoopUrl("arm64"), hash: sha("windows", "arm64") },
      },
      bin: "sigdek.exe",
      checkver: { github: "https://github.com/tektonsoftware/sigdek" },
      autoupdate: {
        architecture: {
          "64bit": { url: scoopUrl("amd64", "$version") },
          arm64: { url: scoopUrl("arm64", "$version") },
        },
        hash: { url: "$baseurl/checksums.txt" },
      },
    },
    null,
    2,
  ) + "\n",
);

// winget: a portable package, one installer per architecture.
const id = "TektonSoftware.SigDek";
const dir = join(wingetOut, "manifests", "t", "TektonSoftware", "SigDek", version);
mkdirSync(dir, { recursive: true });
const schema = "1.6.0";
const header = (type) => `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${schema}.schema.json\n`;
writeFileSync(
  join(dir, `${id}.yaml`),
  `${header("version")}PackageIdentifier: ${id}\nPackageVersion: ${version}\nDefaultLocale: en-US\nManifestType: version\nManifestVersion: ${schema}\n`,
);
writeFileSync(
  join(dir, `${id}.installer.yaml`),
  `${header("installer")}PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: portable
Commands:
- sigdek
ReleaseDate: ${new Date().toISOString().slice(0, 10)}
Installers:
- Architecture: x64
  InstallerUrl: ${base}/${file("windows", "amd64")}
  InstallerSha256: ${sha("windows", "amd64").toUpperCase()}
- Architecture: arm64
  InstallerUrl: ${base}/${file("windows", "arm64")}
  InstallerSha256: ${sha("windows", "arm64").toUpperCase()}
ManifestType: installer
ManifestVersion: ${schema}
`,
);
writeFileSync(
  join(dir, `${id}.locale.en-US.yaml`),
  `${header("defaultLocale")}PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Tekton Software LLC
PublisherUrl: https://sigdek.com
PublisherSupportUrl: https://sigdek.com/docs/
PrivacyUrl: https://sigdek.com/privacy/
PackageName: SigDek
PackageUrl: https://sigdek.com
License: Apache-2.0
LicenseUrl: https://github.com/tektonsoftware/sigdek/blob/main/LICENSE
ShortDescription: ${DESC}.
Description: SigDek records every command, file edit and web request that Claude Code and Cursor make, in a tamper-evident log, and sends it to your team's SigDek audit log. Prompt text, file contents and command output are never recorded.
Moniker: sigdek
Tags:
- ai
- audit
- claude-code
- compliance
- cursor
- soc2
ReleaseNotesUrl: https://github.com/tektonsoftware/sigdek/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: ${schema}
`,
);
console.log(`Homebrew, Scoop and winget manifests written for ${version}`);
